import json
import ollama


def generate_lecture_summary(transcript_text: str):
  """Функция принимает текст лекции, отправляет в локальную Ollama

  и возвращает структурированный JSON с конспектом и таймкодами.
  """

  # Промпт для модели
  prompt = (
      "Ты — ИИ-аналитик учебных видеолекций. Проанализируй текст лекции"
      " с таймкодами и составь конспект.\n"
      "Верни ответ СТРОГО в формате JSON со следующей структурой (без лишнего"
      " текста, только JSON):\n"
      "{\n"
      '  "summary": "Краткое саммари всей лекции в 2-3 предложениях",\n'
      '  "sections": [\n'
      '    {"title": "Название раздела или темы", "timestamp": "00:00:10"}\n'
      "  ]\n"
      "}\n\n"
      f"Текст лекции для анализа:\n{transcript_text}"
  )

  try:
    # Запрос к локальной модели через Ollama
    response = ollama.chat(
        model="llama3",  # Укажи то название модели, которое у вас скачано (например, llama3 или 
        messages=[{"role": "user", "content": prompt}],
        format="json",  # Принудительно просим Ollama отдать чистый JSON
    )

    # Получаем текст ответа
    content = response["message"]["content"]

    # Превращаем строку в Python-словарь
    data = json.loads(content)
    return data

  except Exception as e:
    print(
        f"Произошла ошибка при запросе к Ollama (убедись, что она запущена): {e}"
    )
    return None


# --- Блок тестирования ---
if __name__ == "__main__":
  # Тестовый пример текста с таймкодами
  test_transcript = (
      "[00:00:10] Здравствуйте, сегодня мы разберем основные принципы"
      " объектно-ориентированного программирования.\n[00:01:15] Первый принцип"
      " — это инкапсуляция, она скрывает состояние объекта.\n[00:02:40]"
      " Второй концепт — наследование, которое помогает повторно использовать"
      " код."
  )

  print("🦙 Отправляем тестовый текст в локальную Ollama...")

  # Вызываем функцию
  result = generate_lecture_summary(test_transcript)

  # Выводим результат
  if result:
    print("\n✅ Успех! Получен JSON от локальной модели:")
    print(json.dumps(result, ensure_ascii=False, indent=2))